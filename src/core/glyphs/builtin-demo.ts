export function builtinDemoGlyphSet(): GlyphSetInput {
  const comp: NonNullable<GlyphSetInput['components']> = {};
  for (const [key, [list, extra]] of Object.entries(components)) {
    const { prefer, ...rest } = extra ?? {};
    comp[key] = {
      strokes: strokes(list),
      ...(prefer && Object.keys(prefer).length ? { prefer } : {}),
      ...rest,
    };
  }
  const glyphs: NonNullable<GlyphSetInput['glyphs']> = {};
  for (const token of compositions.trim().split(/\s+/)) {
    const [char, ...rest] = Array.from(token);
    const ids = rest.join('');
    if (!char || !ids || ids === char) continue;
    glyphs[char] = ids;
  }
  for (const [char, scale] of Object.entries(standalone))
    glyphs[char] = { ids: char, adjust: { '': { scale } } };
  for (const [char, value] of Object.entries(punctuation)) glyphs[char] = value;
  return {
    kind: 'glyph-set',
    version: 1,
    id: 'demo',
    name: '演示部件体',
    description:
      'Built-in demo: ~110 stroke-drawn components (common radicals, surrounds and simple characters) and ~420 IDS-composed characters. Not a complete typeface; use fallback "font" for the rest.',
    metrics: { em: 1000, ascent: 880, descent: 120, advance: 1000, space: 320, margin: 80, gap: 40 },
    style: { strokeWidth: 76, cap: 'round', join: 'round', roundness: 0.35, slant: 0, strokeScaling: 0.35 },
    components: comp,
    glyphs,
  };
}
