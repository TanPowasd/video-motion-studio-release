#!/usr/bin/env node
/*
 * Rebuild the taffy layout engine (crates/vmotion-layout) for wasm32-unknown-unknown and
 * embed it as src/core/layout/taffy-wasm.generated.ts (zlib + base64), so every consumer
 * (component worker bundles, CLI, MCP, packaged app) loads the identical engine without a
 * native toolchain or file lookup. Needs `cargo` with the wasm32-unknown-unknown target.
 *
 *   node scripts/build-layout-wasm.mjs          # build + embed
 *   node scripts/build-layout-wasm.mjs --check  # verify the embedded hash matches the crate sources
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import path from 'node:path';
import { repoRootFromModuleUrl } from './repo-root.mjs';
import { zlibSync } from 'fflate';

const root = repoRootFromModuleUrl(import.meta.url);
const crate = path.join(root, 'crates/vmotion-layout');
const output = path.join(root, 'src/core/layout/taffy-wasm.generated.ts');
export const sourceFiles = ['Cargo.toml', 'Cargo.lock', 'src/lib.rs', 'patches/taffy.mjs'];
const sourceHash = () => {
  const h = createHash('sha256');
  for (const f of sourceFiles) h.update(f + '\0' + readFileSync(path.join(crate, f), 'utf8').replace(/\r\n/g, '\n') + '\0');
  return h.digest('hex');
};
if (process.argv.includes('--check')) {
  const embedded = /sourceHash = '([0-9a-f]+)'/.exec(readFileSync(output, 'utf8'))?.[1];
  const current = sourceHash();
  if (embedded !== current) {
    console.error(`layout wasm is stale: embedded ${embedded} vs crate ${current}; run node scripts/build-layout-wasm.mjs`);
    process.exit(1);
  }
  console.log('layout wasm up to date', current.slice(0, 12));
  process.exit(0);
}
const target = process.env.CARGO_TARGET_DIR ?? path.join(crate, 'target');
// taffy 0.9.2 from crates.io (sha256-pinned) + the small fixes in patches/taffy.mjs, vendored
// into crates/vmotion-layout/vendor/taffy (ignored by Git) and wired via [patch.crates-io].
const TAFFY = { version: '0.9.2', sha256: '41ba83ebaf2954d31d05d67340fd46cebe99da2b7133b0dd68d70c65473a437b' };
const vendor = path.join(crate, 'vendor/taffy');
{
  const archive = path.join(crate, `vendor/taffy-${TAFFY.version}.crate`);
  mkdirSync(path.dirname(archive), { recursive: true });
  if (!existsSync(archive)) {
    const response = await fetch(`https://static.crates.io/crates/taffy/taffy-${TAFFY.version}.crate`);
    if (!response.ok) throw new Error(`taffy download failed: ${response.status}`);
    writeFileSync(archive, Buffer.from(await response.arrayBuffer()));
  }
  const digest = createHash('sha256').update(readFileSync(archive)).digest('hex');
  if (digest !== TAFFY.sha256) throw new Error(`taffy crate checksum mismatch: ${digest}`);
  rmSync(vendor, { recursive: true, force: true });
  execFileSync('tar', ['xzf', archive, '-C', path.dirname(archive)]);
  execFileSync('mv', [path.join(crate, `vendor/taffy-${TAFFY.version}`), vendor]);
  const { patches } = await import(path.join(crate, 'patches/taffy.mjs'));
  for (const { file, find, replace } of patches) {
    const full = path.join(vendor, file),
      text = readFileSync(full, 'utf8');
    if (!text.includes(find)) throw new Error(`taffy patch no longer applies to ${file}`);
    writeFileSync(full, text.replace(find, replace));
  }
}
execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: 'inherit',
  env: { ...process.env, CARGO_TARGET_DIR: target },
});
const wasm = readFileSync(path.join(target, 'wasm32-unknown-unknown/release/vmotion_layout.wasm'));
const packed = Buffer.from(zlibSync(wasm, { level: 9 })).toString('base64');
const lines = packed.match(/.{1,120}/g) ?? [];
mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(
  output,
  `/* Generated by scripts/build-layout-wasm.mjs from crates/vmotion-layout (taffy). Do not edit. */\n` +
    `export const sourceHash = '${sourceHash()}';\n` +
    `export const wasmSha256 = '${createHash('sha256').update(wasm).digest('hex')}';\n` +
    `export const wasmBytes = ${wasm.length};\n` +
    `export const wasmZlibBase64 =\n${lines.map((l) => `  '${l}'`).join(' +\n')};\n`,
);
console.log(`embedded ${wasm.length} B wasm (${packed.length} B base64) → ${path.relative(root, output)}`);
